    public function validate(string $raw): ?string
    {
        $nick = mb_trim($raw);

        if (str_contains($raw, '@') || str_contains($nick, '@')) {
            return LangVariant::pick('telegram.registration.errors.nick_forbidden');
        }

        $pattern = '/^[A-Za-zА-Яа-яЁё0-9_\- ]{' . self::MIN_LENGTH . ',' . self::MAX_LENGTH . '}$/u';

        if (preg_match($pattern, $nick) !== 1) {
            return LangVariant::pick('telegram.registration.errors.nick_invalid');
        }

        $folded = $this->foldForBanCheck($nick);

        foreach (self::FORBIDDEN_STEMS as $stem) {
            $stemFolded = $this->foldForBanCheck($stem);

            if (mb_strlen($stemFolded) < 3) {
                continue;
            }

            if (str_contains($folded, $stemFolded)) {
                return LangVariant::pick('telegram.registration.errors.nick_forbidden');
            }
        }

        return null;
    }

    private function foldForBanCheck(string $nick): string
    {
        $folded = mb_strtolower($nick);
        $folded = str_replace('ё', 'е', $folded);
        $folded = str_replace(
            ['0', '1', '3', '4', '5', '7', '@', '$'],
            ['o', 'i', 'e', 'a', 's', 't', 'a', 's'],
            $folded,
        );
        $folded = preg_replace('/[\s_\-]+/u', '', $folded);

        if (! is_string($folded)) {
            throw new RuntimeException('Nick fold failed.');
        }

        $collapsed = preg_replace('/(.)\1+/u', '$1', $folded);

        if (! is_string($collapsed)) {
            throw new RuntimeException('Nick collapse failed.');
        }

        return $collapsed;
    }
